export default function Stack() {
  const [hover, setHover] = useState(null);
  const [phone, setPhone] = useState(false);

  useEffect(() => {
    const query = window.matchMedia("(max-width: 639px)");
    const update = () => setPhone(query.matches);
    update();
    query.addEventListener("change", update);
    return () => query.removeEventListener("change", update);
  }, []);

  const [base, near, big] = phone ? SIZES.phone : SIZES.desktop;
  const sizeOf = (i) => {
    if (hover === null) return base;
    const d = Math.abs(i - hover);
    return d === 0 ? big : d === 1 ? near : base;
  };

  return (
    <div className="mt-12">
      <p className="font-hand text-xl text-zinc-500">my stack</p>

      {/* fixed height, so the row does not jump when an icon grows */}
      <div className="mt-2 flex h-24 items-center gap-1.5 sm:gap-3" onPointerLeave={() => setHover(null)}>
        {stack.map((tool, i) => {
          const size = sizeOf(i);
          const active = hover === i;
          return (
            <div
              key={tool.name}
              role="img"
              aria-label={tool.name}
              onPointerEnter={() => setHover(i)}
              className={`relative flex shrink-0 items-center justify-center rounded-full border transition-all duration-200 ease-out ${
                active
                  ? "border-zinc-300 bg-white text-zinc-900 dark:border-zinc-700 dark:bg-[#181818] dark:text-stone-100"
                  : "border-zinc-200 bg-white text-stone-500 dark:border-zinc-800 dark:bg-[#121212] dark:text-stone-400"
              }`}
              style={{ width: size, height: size }}
            >
              <Icon name={tool.icon} />
              <span
                className={`pointer-events-none absolute bottom-full left-1/2 mb-2 -translate-x-1/2 rounded-lg bg-zinc-900 px-3 py-1.5 text-sm whitespace-nowrap text-zinc-100 transition-opacity duration-150 dark:bg-zinc-100 dark:text-zinc-900 ${
                  active ? "opacity-100" : "opacity-0"
                }`}
              >
                {tool.name}
              </span>
            </div>
          );
        })}

        <span className="ml-1 shrink-0 font-hand text-xl text-zinc-500 sm:ml-2">+ more</span>
      </div>
    </div>
  );
}
